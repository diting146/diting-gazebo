"""Generate the sentry-only RM25 model with the 3D lidar on the gimbal yaw axis.

The shared RM25 model used by the two peripheral robots keeps the lidar rigidly
fixed to ``chassis``.  The sentry needs the lidar mounted on the rotating
``gimbal_yaw`` link instead, so this script derives a separate model from the
shared one and rewrites only the ``lidar_joint`` block and its comment.

Everything else (chassis, wheels, MecanumDrive2, IMU, gimbal controller, the
``lidar_3d`` sensor and its ``ignition_frame_id``) is copied byte-for-byte.

Usage:
    python3 models/generate_sentry_model.py [--source PATH] [--out-dir PATH]

The script is idempotent: repeated runs produce byte-identical output.
"""

import argparse
import os
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

DEFAULT_GAZEBO_SRC = '/home/diting/work/rm_sentry_nav_ws/gazebo/src'

# (0.15, -0.12, 0.134) relative to chassis minus the gimbal yaw joint height
# 0.1336 (model.sdf `gimbal_yaw_odom_joint`) leaves 0.0004 on z.
OLD_POSE = '0.15 -0.12 0.1340 0 0 0'
NEW_POSE = '0.15 -0.12 0.0004 0 0 0'

JOINT_RE = re.compile(
    r'[ \t]*<joint\s+name="lidar_joint"[^>]*>.*?</joint>',
    re.DOTALL,
)
COMMENT_RE = re.compile(
    r'[ \t]*<!--[ \t]*3D LiDAR mounted on gimbal_yaw.*?-->',
    re.DOTALL,
)
CONTROLLER_RE = re.compile(
    r'[ \t]*<plugin[^>]*joint-position-controller[^>]*>.*?</plugin>',
    re.DOTALL,
)

GIMBAL_CMD_TOPIC = '/sentry_robot1/gimbal_yaw_cmd'
GIMBAL_DAMPING = '5.0'
GIMBAL_FRICTION = '1.0'
GIMBAL_INITIAL_POSITION = '0.0'
GIMBAL_GAINS = {
    'p_gain': '50.0',
    'i_gain': '0.0',
    'd_gain': '5.0',
    'i_max': '10.0',
    'i_min': '-10.0',
    'cmd_max': '200.0',
    'cmd_min': '-200.0',
}

GIMBAL_JOINT_RE = re.compile(
    r'[ \t]*<joint\s+name="gimbal_yaw_joint"[^>]*>.*?</joint>',
    re.DOTALL,
)

NEW_COMMENT_LINES = (
    '<!-- 3D LiDAR is mounted on gimbal_yaw so it rotates with the turret.',
    '     Offsets are relative to gimbal_yaw: (0.15, -0.12, 0.0004), i.e.',
    '     the same physical mount as the chassis-relative (0.15,-0.12,0.134)',
    '     because gimbal_yaw_odom_joint sits 0.1336 above chassis. -->',
)

MODEL_CONFIG = """<?xml version="1.0"?>
<model>
  <name>sentry_rm25</name>
  <version>1.0</version>
  <sdf version="1.8">model.sdf</sdf>
  <author>
    <name>diting</name>
    <email>diting@example.com</email>
  </author>
  <description>
    RM25 sentry body with the 3D lidar mounted on the rotating gimbal yaw axis.
    Generated by generate_sentry_model.py; do not edit by hand.
  </description>
</model>
"""


def _patch_joint(match: re.Match) -> str:
    """Rewrite the single lidar_joint block onto gimbal_yaw."""
    block = match.group(0)
    for needle in ('relative_to="chassis"', OLD_POSE, '<parent>chassis</parent>'):
        if block.count(needle) != 1:
            raise SystemExit(
                f'error: expected exactly one {needle!r} inside lidar_joint, '
                f'found {block.count(needle)}'
            )
    block = block.replace('relative_to="chassis"', 'relative_to="gimbal_yaw"')
    block = block.replace(OLD_POSE, NEW_POSE)
    block = block.replace('<parent>chassis</parent>', '<parent>gimbal_yaw</parent>')
    return block


def _patch_comment(match: re.Match) -> str:
    """Replace the stale 'mounted on gimbal_yaw' comment with an accurate one."""
    block = match.group(0)
    indent = block[: len(block) - len(block.lstrip(' \t'))]
    return '\n'.join(indent + line for line in NEW_COMMENT_LINES)


def _patch_controller(match: re.Match) -> str:
    """Retune the gimbal controller and give it an explicit command topic.

    The stock gains (p=1000, i=200, d=200, cmd_max=2000) are unstable on this
    light yaw link: the joint self-oscillates instead of tracking the command.
    """
    block = match.group(0)
    for name, value in GIMBAL_GAINS.items():
        block, count = re.subn(
            rf'<{name}>[^<]*</{name}>', f'<{name}>{value}</{name}>', block
        )
        if count != 1:
            raise SystemExit(
                f'error: expected exactly one <{name}> in the gimbal controller, '
                f'found {count}'
            )
    plugin_indent = block[: len(block) - len(block.lstrip(' \t'))]
    child = re.search(r'(?m)^([ \t]*)<joint_name>', block)
    indent = child.group(1) if child else plugin_indent + '\t'
    close = block.rfind('</plugin>')
    body = block[:close].rstrip()
    if '<initial_position>' not in body:
        body += (
            f'\n{indent}<initial_position>{GIMBAL_INITIAL_POSITION}'
            f'</initial_position>'
        )
    if '<topic>' not in body:
        body += f'\n{indent}<topic>{GIMBAL_CMD_TOPIC}</topic>'
    return f'{body}\n{plugin_indent}</plugin>'


def _patch_gimbal_joint(match: re.Match) -> str:
    """Lower the yaw joint damping/friction so the controller can move it.

    The shared model uses damping 5000 and friction 2000 on this joint while
    both the joint effort limit and the controller cmd_max are 2000, so the
    actuator can never overcome the friction and the joint stays at zero.
    """
    block = match.group(0)
    for needle, replacement in (
        ('<damping>5000.0</damping>', f'<damping>{GIMBAL_DAMPING}</damping>'),
        ('<friction>2000.0</friction>', f'<friction>{GIMBAL_FRICTION}</friction>'),
    ):
        if block.count(needle) != 1:
            raise SystemExit(
                f'error: expected exactly one {needle!r} in gimbal_yaw_joint, '
                f'found {block.count(needle)}'
            )
        block = block.replace(needle, replacement)
    return block


def _verify(output_text: str) -> None:
    """Assert the generated model has the expected lidar mount and parses."""
    root = ET.fromstring(output_text)
    joints = [
        joint for joint in root.iter('joint')
        if joint.get('name') == 'lidar_joint'
    ]
    if len(joints) != 1:
        raise SystemExit(
            f'error: expected exactly one lidar_joint, found {len(joints)}'
        )
    joint = joints[0]
    parent = joint.find('parent')
    child = joint.find('child')
    pose = joint.find('pose')
    if parent is None or parent.text != 'gimbal_yaw':
        raise SystemExit(f'error: lidar_joint parent is {parent!r}, expected gimbal_yaw')
    if child is None or child.text != 'lidar_link':
        raise SystemExit(f'error: lidar_joint child is {child!r}, expected lidar_link')
    if pose is None or pose.get('relative_to') != 'gimbal_yaw':
        raise SystemExit('error: lidar_joint pose is not relative to gimbal_yaw')
    if (pose.text or '').split() != NEW_POSE.split():
        raise SystemExit(f'error: lidar_joint pose is {pose.text!r}, expected {NEW_POSE!r}')
    sensors = [s for s in root.iter('sensor') if s.get('name') == 'lidar_3d']
    if len(sensors) != 1:
        raise SystemExit(f'error: expected exactly one lidar_3d sensor, found {len(sensors)}')
    frame_id = sensors[0].find('ignition_frame_id')
    if frame_id is None or frame_id.text != 'lidar_link':
        raise SystemExit('error: lidar_3d ignition_frame_id changed unexpectedly')


def generate(source: Path, out_dir: Path) -> Path:
    """Read the shared RM25 model and write the sentry variant."""
    if not source.is_file():
        raise SystemExit(f'error: source model not found: {source}')

    text = source.read_text(encoding='utf-8')

    text, joint_count = JOINT_RE.subn(_patch_joint, text)
    if joint_count != 1:
        raise SystemExit(
            f'error: expected to patch exactly 1 lidar_joint, patched {joint_count}'
        )

    text, comment_count = COMMENT_RE.subn(_patch_comment, text)
    if comment_count != 1:
        raise SystemExit(
            'error: expected to patch exactly 1 lidar comment, '
            f'patched {comment_count}'
        )

    text, controller_count = CONTROLLER_RE.subn(_patch_controller, text)
    if controller_count != 1:
        raise SystemExit(
            'error: expected to patch exactly 1 gimbal controller, '
            f'patched {controller_count}'
        )
    if f'<topic>{GIMBAL_CMD_TOPIC}</topic>' not in text:
        raise SystemExit('error: gimbal command topic was not injected')

    text, gimbal_count = GIMBAL_JOINT_RE.subn(_patch_gimbal_joint, text)
    if gimbal_count != 1:
        raise SystemExit(
            'error: expected to patch exactly 1 gimbal_yaw_joint, '
            f'patched {gimbal_count}'
        )

    # This is a mounting spacer, not a second uncontrolled yaw axis.
    # ROS publishes chassis -> gimbal_yaw_odom as a static transform.
    mount_pattern = r'(<joint name="gimbal_yaw_odom_joint" type=")revolute("[^>]*>)(.*?)(</joint>)'
    def fix_mount(match):
        body = re.sub(r'<axis>.*?</axis>', '', match.group(3), flags=re.DOTALL)
        return match.group(1) + 'fixed' + match.group(2) + body + match.group(4)
    text, mount_count = re.subn(mount_pattern, fix_mount, text, flags=re.DOTALL)
    if mount_count != 1:
        raise SystemExit('error: expected exactly one gimbal mounting joint')

    _verify(text)

    out_dir.mkdir(parents=True, exist_ok=True)
    model_path = out_dir / 'model.sdf'
    model_path.write_text(text, encoding='utf-8')
    (out_dir / 'model.config').write_text(MODEL_CONFIG, encoding='utf-8')
    return model_path


def parse_args(argv):
    """Parse command line arguments."""
    parser = argparse.ArgumentParser(description=__doc__)
    gazebo_src = os.environ.get('GAZEBO_SRC', DEFAULT_GAZEBO_SRC)
    parser.add_argument(
        '--source',
        type=Path,
        default=Path(gazebo_src)
        / 'rmu_gazebo_simulator'
        / 'rmu_gazebo_simulator'
        / 'resource'
        / 'models'
        / 'rm25_example_robot'
        / 'model.sdf',
        help='shared RM25 model.sdf to derive from',
    )
    parser.add_argument(
        '--out-dir',
        type=Path,
        default=Path(__file__).resolve().parent / 'sentry_rm25',
        help='directory receiving model.sdf and model.config',
    )
    return parser.parse_args(argv)


def main(argv=None):
    """Generate the sentry model and report the result."""
    args = parse_args(argv)
    model_path = generate(args.source, args.out_dir)
    print(f'source: {args.source}')
    print(f'wrote:  {model_path}')
    print(f'wrote:  {model_path.parent / "model.config"}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
